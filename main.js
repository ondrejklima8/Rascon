    const copyToast = document.getElementById('copy-toast');
    let toastTimer = null;

    function showToast() {
      if (!copyToast) return;
      copyToast.classList.add('is-visible');
      if (toastTimer) clearTimeout(toastTimer);
      toastTimer = setTimeout(() => {
        copyToast.classList.remove('is-visible');
      }, 2000);
    }

    async function copyToClipboard(text) {
      try {
        if (navigator.clipboard && window.isSecureContext) {
          await navigator.clipboard.writeText(text);
          return true;
        }
      } catch (err) { /* blocked by permissions policy in iframe */ }
      try {
        const ta = document.createElement('textarea');
        ta.value = text;
        ta.setAttribute('readonly', '');
        ta.style.position = 'fixed';
        ta.style.left = '-9999px';
        document.body.appendChild(ta);
        ta.focus();
        ta.select();
        const ok = document.execCommand('copy');
        document.body.removeChild(ta);
        return ok;
      } catch (err) {
        return false;
      }
    }

    document.querySelectorAll('.copyable').forEach(el => {
      el.addEventListener('click', async (e) => {
        e.preventDefault();
        const type = el.getAttribute('data-copy-type');
        let value = '';
        let href = '';

        if (type === 'phone') {
          value = el.getAttribute('data-copy-value') || '';
          href = el.getAttribute('data-href') || '';
        } else if (type === 'email') {
          const user = el.getAttribute('data-email-user');
          const domain = el.getAttribute('data-email-domain');
          if (user && domain) {
            value = user + '@' + domain;
            href = 'mailto:' + value;
          }
        }

        if (value) {
          const ok = await copyToClipboard(value);
          if (ok) showToast();
        }

        // Open native handler (mail / phone app)
        if (href) {
          window.location.href = href;
        }
      });
    });

