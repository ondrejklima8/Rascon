/* Typewriter rotating word — types then erases */
    (function() {
      var el = document.getElementById('rotating-word');
      var prefixEl = document.getElementById('hero-prefix');
      if (!el) return;
      var wordsByLang = {
        cs: ['důvěře', 'odbornosti', 'kvalitě', 'termínech'],
        en: ['trust', 'expertise', 'quality', 'deadlines']
      };
      var prefixes = { cs: 'Stavíme na', en: 'Built on' };
      function getLang() {
        return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'cs';
      }
      var words = wordsByLang[getLang()];
      var wordIdx = 0;
      var charIdx = 0;
      var isDeleting = false;
      var typeSpeed = 90;
      var deleteSpeed = 50;
      var pauseAfterType = 2000;
      var pauseAfterDelete = 400;
      var timerId = null;

      function tick() {
        var currentWord = words[wordIdx];
        if (!isDeleting) {
          charIdx++;
          el.textContent = currentWord.substring(0, charIdx);
          if (charIdx === currentWord.length) {
            isDeleting = true;
            timerId = setTimeout(tick, pauseAfterType);
            return;
          }
          timerId = setTimeout(tick, typeSpeed);
        } else {
          charIdx--;
          el.textContent = currentWord.substring(0, charIdx);
          if (charIdx === 0) {
            isDeleting = false;
            wordIdx = (wordIdx + 1) % words.length;
            timerId = setTimeout(tick, pauseAfterDelete);
            return;
          }
          timerId = setTimeout(tick, deleteSpeed);
        }
      }

      // Start after page load animation
      timerId = setTimeout(function() {
        el.textContent = '';
        tick();
      }, 1800);

      window.addEventListener('rascon:lang-changed', function() {
        // Cancel any running timer to prevent parallel chains
        if (timerId) clearTimeout(timerId);
        words = wordsByLang[getLang()];
        if (prefixEl) prefixEl.textContent = prefixes[getLang()];
        wordIdx = 0;
        charIdx = 0;
        isDeleting = false;
        el.textContent = '';
        tick();
      });
    })();

