    /* ===========================================================
       I18N — Apply translations
       =========================================================== */
    function applyLanguage(lang) {
      if (!translations[lang]) return;
      const dict = translations[lang];

      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key] !== undefined) el.textContent = dict[key];
      });
      document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (dict[key] !== undefined) el.innerHTML = dict[key];
      });
      document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
      });

      document.documentElement.setAttribute('lang', lang);
      window.dispatchEvent(new CustomEvent('rascon:lang-changed', { detail: { lang } }));
      document.querySelectorAll('.lang-switcher button, .mobile-menu-lang button').forEach(btn => {
        btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
      });
      localStorage.setItem('rascon-lang', lang);
    }

    document.querySelectorAll('.lang-switcher button, .mobile-menu-lang button').forEach(btn => {
      btn.addEventListener('click', () => applyLanguage(btn.getAttribute('data-lang')));
    });

    // Load saved preference
    const savedLang = localStorage.getItem('rascon-lang');
    if (savedLang && translations[savedLang]) applyLanguage(savedLang);

