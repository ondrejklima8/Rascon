/* Typewriter rotating word — types then erases */
    (function() {
      var el = document.getElementById('rotating-word');
      if (!el) return;
      var wordsByLang = {
        cs: ['důvěře', 'odbornosti', 'kvalitě', 'termínech'],
        en: ['trust', 'expertise', 'quality', 'deadlines']
      };
      function getLang() {
        return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'cs';
      }
      var words = wordsByLang[getLang()];
      var wordIdx = 0;
      var charIdx = 0;
      var isDeleting = false;
      var typeSpeed = 90;
      var deleteSpeed = 50;
      var pauseAfterType = 2000;
      var pauseAfterDelete = 400;

      function tick() {
        var currentWord = words[wordIdx];
        if (!isDeleting) {
          charIdx++;
          el.textContent = currentWord.substring(0, charIdx);
          if (charIdx === currentWord.length) {
            isDeleting = true;
            setTimeout(tick, pauseAfterType);
            return;
          }
          setTimeout(tick, typeSpeed);
        } else {
          charIdx--;
          el.textContent = currentWord.substring(0, charIdx);
          if (charIdx === 0) {
            isDeleting = false;
            wordIdx = (wordIdx + 1) % words.length;
            setTimeout(tick, pauseAfterDelete);
            return;
          }
          setTimeout(tick, deleteSpeed);
        }
      }

      // Start after page load animation
      setTimeout(function() {
        el.textContent = '';
        tick();
      }, 1800);

      window.addEventListener('rascon:lang-changed', function() {
        words = wordsByLang[getLang()];
        wordIdx = 0;
        charIdx = 0;
        isDeleting = false;
        el.textContent = '';
        tick();
      });
    })();

