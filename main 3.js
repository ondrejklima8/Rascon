    /* ===========================================================
       SCROLL REVEAL
       =========================================================== */
    const revealObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          revealObserver.unobserve(entry.target);
        }
      });
    }, { threshold: 0.08, rootMargin: '0px 0px -30px 0px' });
    document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

    /* ===========================================================
       COUNTER ANIMATION
       =========================================================== */
    const counterObserver = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        const target = parseInt(el.dataset.countTo, 10);
        if (isNaN(target) || el.dataset.counted) return;
        el.dataset.counted = 'true';
        const duration = 1400;
        const start = performance.now();
        const tick = now => {
          const progress = Math.min((now - start) / duration, 1);
          const eased = 1 - Math.pow(1 - progress, 3);
          el.textContent = Math.floor(target * eased);
          if (progress < 1) requestAnimationFrame(tick);
        };
        requestAnimationFrame(tick);
      });
    }, { threshold: 0.5 });
    document.querySelectorAll('[data-count-to]').forEach(el => counterObserver.observe(el));

    /* ===========================================================
       EMAIL INJECTION (anti-Cloudflare-scraping)
       Build email addresses at runtime from user/domain attributes
       so Cloudflare's email obfuscation doesn't mangle them.
       =========================================================== */
    function injectEmails() {
      document.querySelectorAll('[data-email-user][data-email-domain]').forEach(el => {
        const user = el.getAttribute('data-email-user');
        const domain = el.getAttribute('data-email-domain');
        const fullEmail = user + '@' + domain;
        const display = el.querySelector('[data-email-display]');
        if (display) display.textContent = fullEmail;
        // If element is an <a>, also set href
        if (el.tagName === 'A') {
          el.setAttribute('href', 'mailto:' + fullEmail);
        }
      });
    }
    injectEmails();

    /* ===========================================================
       COPY-TO-CLIPBOARD WITH TOAST FEEDBACK
       Triggers tel:/mailto: AND copies value to clipboard
       =========================================================== */
    const copyToast = document.getElementById('copy-toast');
    let toastTimer = null;

    function showToast() {
      if (!copyToast) return;
      copyToast.classList.add('is-visible');
      if (toastTimer) clearTimeout(toastTimer);
      toastTimer = setTimeout(() => {
        copyToast.classList.remove('is-visible');
      }, 2000);
    }

    async function copyToClipboard(text) {
      try {
        if (navigator.clipboard && window.isSecureContext) {
          await navigator.clipboard.writeText(text);
          return true;
        }
      } catch (err) { /* blocked by permissions policy in iframe */ }
      try {
        const ta = document.createElement('textarea');
        ta.value = text;
        ta.setAttribute('readonly', '');
        ta.style.position = 'fixed';
        ta.style.left = '-9999px';
        document.body.appendChild(ta);
        ta.focus();
        ta.select();
        const ok = document.execCommand('copy');
        document.body.removeChild(ta);
        return ok;
      } catch (err) {
        return false;
      }
    }

    document.querySelectorAll('.copyable').forEach(el => {
      el.addEventListener('click', async (e) => {
        e.preventDefault();
        const type = el.getAttribute('data-copy-type');
        let value = '';
        let href = '';

        if (type === 'phone') {
          value = el.getAttribute('data-copy-value') || '';
          href = el.getAttribute('data-href') || '';
        } else if (type === 'email') {
          const user = el.getAttribute('data-email-user');
          const domain = el.getAttribute('data-email-domain');
          if (user && domain) {
            value = user + '@' + domain;
            href = 'mailto:' + value;
          }
        }

        if (value) {
          const ok = await copyToClipboard(value);
          if (ok) showToast();
        }

        // Open native handler (mail / phone app)
        if (href) {
          window.location.href = href;
        }
      });
    });

